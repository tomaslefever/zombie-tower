"""Pack the game's MP3s into audio-data.js so the realistic version also has sound when opened by double click.

Browsers block a page opened from disk (file://) from reading files next to it with fetch(),
but they do let it load a <script> from the same folder. The game loads this file only in that case;
over http(s) it fetches the MP3s directly.

Run from the project folder after changing any sound:  python tools/build-audio-data.py
"""
import base64
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FILES = ["hive-mind.mp3"] + sorted(f"sfx/{p.name}" for p in (ROOT / "sfx").glob("*.mp3"))

data = {name: base64.b64encode((ROOT / name).read_bytes()).decode("ascii") for name in FILES}
out = ROOT / "audio-data.js"
out.write_text(
    "// Generated by tools/build-audio-data.py; do not edit. MP3s as base64, keyed by path.\n"
    "window.TORRE_AUDIO=" + json.dumps(data, separators=(",", ":")) + ";\n",
    encoding="ascii",
)
print(f"{out.name}: {len(FILES)} files, {out.stat().st_size / 1e6:.1f} MB")
